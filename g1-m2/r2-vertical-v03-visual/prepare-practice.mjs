import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { hashBytes, runT12 } from '../r2-vertical-v03-d/t12-witness.js';
import { canonicalBytes } from '../r2-vertical-v03-a/src/world.js';
import { guides } from './practice-guide.mjs';

const check = process.argv.includes('--check');
const file = name => new URL(name, import.meta.url);
const engine = file('./practice-engine.mjs');
const dataFile = file('./practice-data.json');
const { outputFiles: [bundle] } = await build({
  absWorkingDir: fileURLToPath(file('./')),
  entryPoints: ['./practice-world.mjs'],
  alias: { 'node:crypto': './browser-sha.mjs' },
  bundle: true, platform: 'browser', target: 'es2022', format: 'esm', minify: true, write: false,
  outfile: fileURLToPath(engine),
  banner: { js: '// Generated by prepare-practice.mjs from the versioned practice policy.' },
});

const { report, states } = runT12();
const prefixes = Object.fromEntries(Object.entries(guides).filter(([, guide]) => guide.sourceStep).map(([id, { sourceStep }]) => {
  const step = report.steps[sourceStep - 1];
  const nextSeq = states.get(step.label).nextEventSeq;
  const transactions = report.journal.transactions.findIndex(packet => packet[0].eventSeq === nextSeq);
  assert(transactions > 0, id);
  return [id, { sourceStep, transactions, digest: step.afterSha256 }];
}));
const data = {
  journal: {
    ...report.journal,
    transactions: report.journal.transactions.slice(0, Math.max(...Object.values(prefixes).map(p => p.transactions))),
  },
  prefixes,
};
const bytes = JSON.stringify(data) + '\n';
if (check) {
  assert.equal(readFileSync(engine, 'utf8'), bundle.text, 'Run npm run build:practice to refresh the browser bundle');
  assert.equal(readFileSync(dataFile, 'utf8'), bytes, 'Run npm run build:practice to refresh the starting histories');
} else {
  writeFileSync(engine, bundle.text);
  writeFileSync(dataFile, bytes);
}
const { replayT12, openPracticeCheckpoint, replayPractice } = await import(engine.href);
for (const [id, prefix] of Object.entries(prefixes)) {
  const journal = { ...data.journal, transactions: data.journal.transactions.slice(0, prefix.transactions) };
  const historical = replayT12(journal);
  assert.equal(hashBytes(historical.bytes()), prefix.digest, id);
  const world = openPracticeCheckpoint(journal);
  for (const field of ['occupancy', 'constructionEdges', 'support', 'spaceIntents', 'boundaryPatches', 'passages']) {
    assert.equal(canonicalBytes(world.state.snapshot[field]), canonicalBytes(historical.state.snapshot[field]), `${id} ${field}`);
  }
  assert.equal(replayPractice(world.journal()).bytes(), world.bytes(), id);
}
console.log(`Browser practice policy verified against ${Object.keys(prefixes).length} T12 checkpoints | ${bundle.contents.length} bytes of engine`);
